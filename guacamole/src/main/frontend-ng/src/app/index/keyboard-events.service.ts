import { Injectable } from '@angular/core';
import { Subject } from 'rxjs';

/**
 * A key event dispatched by the global Guacamole.Keyboard. Listeners may
 * call preventDefault() to stop further handling of the event, exactly as
 * with the guacBeforeKeydown/guacKeydown/guacBeforeKeyup/guacKeyup events
 * broadcast by the AngularJS application.
 */
export class GuacKeyEvent {

    defaultPrevented = false;

    constructor(readonly keysym: number, readonly keyboard: Guacamole.Keyboard) {}

    preventDefault(): void {
        this.defaultPrevented = true;
    }

}

/**
 * Service exposing the global keyboard and the key events it produces.
 * Subjects deliver events synchronously, so dispatchers can inspect
 * defaultPrevented immediately after emitting.
 */
@Injectable({ providedIn: 'root' })
export class KeyboardEventsService {

    /** The keyboard receiving all key events not handled elsewhere. */
    keyboard?: Guacamole.Keyboard;

    readonly beforeKeydown = new Subject<GuacKeyEvent>();
    readonly keydown = new Subject<GuacKeyEvent>();
    readonly beforeKeyup = new Subject<GuacKeyEvent>();
    readonly keyup = new Subject<GuacKeyEvent>();

    /**
     * Key events generated by on-screen input methods (the on-screen
     * keyboard and text input), which should be sent to the focused client
     * but are not subject to the browser's keyboard.
     */
    readonly syntheticKeydown = new Subject<number>();
    readonly syntheticKeyup = new Subject<number>();

    /**
     * Updates the state of modifier keys based on the given mouse or touch
     * event, which may carry modifier information.
     */
    updateModifiers(event: Event): void {
        // Not yet included within the guacamole-common-js type definitions
        (this.keyboard as { updateModifiers?: (event: Event) => void } | undefined)?.updateModifiers?.(event);
    }

    /**
     * Releases all currently-pressed keys.
     */
    reset(): void {
        this.keyboard?.reset();
    }

}
