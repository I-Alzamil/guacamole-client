import { definePatches } from './patches';

/**
 * Loads the JavaScript and HTML patches of all installed extensions, exactly
 * as provided to the AngularJS application: "app.js" (generated by the web
 * application from the "js" files of each extension's manifest) and the
 * patches returned by the "api/patches" REST endpoint (the "html" files of
 * each manifest). This must complete before the application starts, such
 * that extensions can register field types, etc.
 */
export async function loadExtensions(): Promise<void> {

    const build = document.querySelector<HTMLMetaElement>('meta[name="build"]')?.content ?? '';
    const url = 'app.js?b=' + encodeURIComponent(build);

    let source: string;
    let patches: string[];
    try {
        const [scriptResponse, patchResponse] = await Promise.all([fetch(url), fetch('api/patches')]);
        source = scriptResponse.ok ? await scriptResponse.text() : '';
        patches = patchResponse.ok ? await patchResponse.json() : [];
    }
    catch (e) {
        console.error('Extensions could not be loaded:', e);
        return;
    }

    // Extension components and patches are compiled at runtime, as they are
    // not part of the application build. Both the compiler and the modules
    // available to extensions are loaded only if needed, as they are large.
    // As the script provided by the web application is never empty (it
    // always verifies the cached version of the application), whether any
    // extension needs them is determined by whether the script references
    // the modules of the application (see extension-sdk/build.mjs).
    if (patches.length || source.includes('GuacamoleFrontend')) {

        const [{ EXTENSION_MODULES }] = await Promise.all([
            import('./extension-modules'),
            import('@angular/compiler')
        ]);

        (globalThis as any).GuacamoleFrontend = { modules: EXTENSION_MODULES };

    }

    installAngularJSPlaceholder();

    if (source.trim()) {
        await new Promise<void>(resolve => {
            const script = document.createElement('script');
            script.src = url;
            script.onload = script.onerror = () => resolve();
            document.head.appendChild(script);
        });
    }

    definePatches(patches);

}

/**
 * Defines a placeholder for the global "angular" object of AngularJS, such
 * that installed extensions which were built for the AngularJS application
 * are skipped (with a warning) rather than preventing all other extensions
 * from loading. Such extensions must be built with the "angular-frontend"
 * Maven profile to work with this application.
 */
function installAngularJSPlaceholder(): void {

    const warned = new Set<string>();

    const ignored: object = new Proxy(function () { /* No-op */ }, {
        get: (target, property) => property === 'requires' ? [] : () => ignored,
        apply: () => ignored
    });

    (globalThis as any).angular = new Proxy({}, {
        get: (target, property) => (name?: string) => {
            if (property === 'module' && name && name !== 'index' && !warned.has(name)) {
                warned.add(name);
                console.warn('Ignoring AngularJS module "' + name + '" of an extension built '
                    + 'for the AngularJS frontend. Rebuild the extension with the '
                    + '"angular-frontend" profile to use it with this frontend.');
            }
            return ignored;
        }
    });

}
